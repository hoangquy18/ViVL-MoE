#!/usr/bin/env python
"""Generate docs/configs.md from the dataclasses in vivlmoe/config/schema.py.

Field descriptions are the trailing ``# comment`` on each field line, so the schema stays the single
source of truth. Run: ``python scripts/gen_config_docs.py`` (writes docs/configs.md).
"""

from __future__ import annotations

import dataclasses
import inspect
import re
import sys
import typing
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO_ROOT))

from vivlmoe.config import schema  # noqa: E402

FIELD_RE = re.compile(
    r"^\s*(?P<name>[A-Za-z_][A-Za-z0-9_]*)\s*:\s*(?P<ann>.+?)(?:\s*=\s*(?P<default>.+?))?\s*(?:#\s*(?P<comment>.*))?$"
)


def field_comments(cls: type) -> dict[str, str]:
    """Map field name -> trailing comment text parsed from the class source."""
    comments: dict[str, str] = {}
    try:
        src = inspect.getsource(cls)
    except OSError:
        return comments
    for line in src.splitlines():
        m = FIELD_RE.match(line)
        if not m or line.strip().startswith(("def ", "@", "class ", "#", '"""')):
            continue
        if m.group("comment"):
            comments[m.group("name")] = m.group("comment").strip()
    return comments


def type_name(tp: object) -> str:
    origin = typing.get_origin(tp)
    args = typing.get_args(tp)
    if origin is typing.Literal:
        return " \\| ".join(repr(a) for a in args)
    if origin is typing.Union or (origin is not None and origin.__name__ == "UnionType"):
        return " \\| ".join(type_name(a) for a in args)
    if origin in (list, dict, tuple):
        inner = ", ".join(type_name(a) for a in args) if args else ""
        return f"{origin.__name__}[{inner}]"
    if dataclasses.is_dataclass(tp) and isinstance(tp, type):
        return f"[{tp.__name__}](#{tp.__name__.lower()})"
    return getattr(tp, "__name__", str(tp)).replace("NoneType", "None")


def default_repr(f: dataclasses.Field) -> str:
    if f.default is not dataclasses.MISSING:
        return f"`{f.default!r}`"
    if f.default_factory is not dataclasses.MISSING:  # type: ignore[misc]
        try:
            value = f.default_factory()  # type: ignore[misc]
        except Exception:  # noqa: BLE001
            return "(factory)"
        if dataclasses.is_dataclass(value):
            return "(defaults)"
        return f"`{value!r}`"
    return "**required**"


def render(cls: type, seen: set[str], out: list[str]) -> None:
    if cls.__name__ in seen:
        return
    seen.add(cls.__name__)
    doc = inspect.getdoc(cls) or ""
    if doc.startswith(cls.__name__ + "("):  # auto-generated dataclass signature, not a docstring
        doc = ""
    out.append(f"### {cls.__name__}\n")
    if doc:
        out.append(doc + "\n")
    out.append("| field | type | default | description |\n|---|---|---|---|")
    comments = field_comments(cls)
    hints = typing.get_type_hints(cls)
    nested: list[type] = []
    for f in dataclasses.fields(cls):
        tp = hints[f.name]
        out.append(
            f"| `{f.name}` | {type_name(tp)} | {default_repr(f)} | {comments.get(f.name, '')} |"
        )
        for candidate in (tp, *typing.get_args(tp)):
            if dataclasses.is_dataclass(candidate) and isinstance(candidate, type):
                nested.append(candidate)
    out.append("")
    for sub in nested:
        render(sub, seen, out)


def main() -> int:
    out = [
        "# Configuration reference",
        "",
        "Generated by `scripts/gen_config_docs.py` from `vivlmoe/config/schema.py` — do not edit by hand.",
        "",
        "## Loading rules",
        "",
        "* `_include: [a.yaml, b.yaml]` are deep-merged in order (later wins), then the file's own keys win;",
        "  paths are relative to the including file (or the repo root when they start with `configs/`).",
        "* CLI overrides `key.path=value` (YAML-parsed) are merged last: `scripts/train.py --config c.yaml train.max_steps=10`.",
        "* Unknown keys, wrong types and cross-field violations raise `ConfigError` with the full dotted path.",
        "* `model.from_checkpoint: <ckpt>` replaces the whole `model` section with the one stored in the checkpoint",
        "  sidecar (`<ckpt>.meta.json`); `model_overrides` are merged on top. Stabilizer switches must match the",
        "  checkpoint unless `task.allow_stabilizer_override: true`.",
        "* Never use the YAML-boolean words `on/off/yes/no` as string values (PyYAML parses them as booleans).",
        "",
        "## Sections",
        "",
    ]
    render(schema.RunConfig, set(), out)
    path = REPO_ROOT / "docs" / "configs.md"
    path.write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"wrote {path} ({len(out)} lines)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
